#!/bin/bash

# -------------------------------------------------------------------------
# Точка входа: инициализация планировщика задач
# -------------------------------------------------------------------------
# Все переменные (INGESTOR_CRON_SCHEDULE, INGESTOR_RUN_ON_STARTUP) 
# попадают сюда НАПРЯМУЮ из файла .env благодаря директиве `env_file: - .env` 
# в секции сервиса ingestor файла compose.yaml.

set -e

CRON_FILE="/tmp/crontab.meteo"


# -------------------------------------------------------------------------
# 1. Валидация обязательных параметров (Fail-fast)
# -------------------------------------------------------------------------
# Если cron-строка не передана, прерываем запуск сразу, чтобы не генерировать
# битый файл расписания и не вводить планировщик в заблуждение.

if [ -z "$INGESTOR_CRON_SCHEDULE" ]; then
    echo "[ИНИЦИАЛИЗАЦИЯ] ❌ КРИТИЧЕСКАЯERROR: Переменная INGESTOR_CRON_SCHEDULE не задана."
    echo "[ИНИЦИАЛИЗАЦИЯ] Проверьте, что в файле .env есть строка вида:"
    echo "[ИНИЦИАЛИЗАЦИЯ] INGESTOR_CRON_SCHEDULE=10 0,3,6,9,12,15,18,21 * * *"
    exit 1
fi

echo "[ИНИЦИАЛИЗАЦИЯ] Формирование таблицы расписания..."
echo "[ИНИЦИАЛИЗАЦИЯ] Получено расписание: '$INGESTOR_CRON_SCHEDULE'"


# -------------------------------------------------------------------------
# 2. Немедленный запуск при старте контейнера (опционально)
# -------------------------------------------------------------------------
# Переменная INGESTOR_RUN_ON_STARTUP также берется напрямую из .env.
# Если она равна "true", мы запускаем задачу один раз синхронно.
# Запуск обернут в подпроцесс (...), чтобы ошибка выполнения python 
# не прерывала весь скрипт из-за 'set -e'. Планировщик продолжит работу.

if [ "${INGESTOR_RUN_ON_STARTUP:-false}" = "true" ]; then
    echo "[ИНИЦИАЛИЗАЦИЯ] 🚀 Немедленный запуск задачи (INGESTOR_RUN_ON_STARTUP=true)"
    (
        cd /application && python -u -m codebase.main
    ) || echo "[ИНИЦИАЛИЗАЦИЯ] ⚠️ Немедленный запуск завершился с ошибкой, но планировщик продолжит работу по расписанию."
    echo "[ИНИЦИАЛИЗАЦИЯ] ✅ Немедленный запуск завершён."
fi


# -------------------------------------------------------------------------
# 3. Регистрация задачи
# -------------------------------------------------------------------------
# Формат файла расписания для supercronic: <cron-выражение> <команда>
# Использование 'python -u' отключает буферизацию вывода для корректных логов.
# Использование '-m codebase.main' гарантирует работу относительных импортов.

echo "$INGESTOR_CRON_SCHEDULE cd /application && python -u -m codebase.main" > "$CRON_FILE"

echo "[ИНИЦИАЛИЗАЦИЯ] Задача зарегистрирована в $CRON_FILE"
echo "[ИНИЦИАЛИЗАЦИЯ] Передача управления планировщику Supercronic."


# -------------------------------------------------------------------------
# 4. Активация исполнительного механизма
# -------------------------------------------------------------------------
# Команда exec заменяет текущий процесс bash на процесс supercronic.
# Это позволяет контейнеру корректно обрабатывать сигналы остановки (SIGTERM/SIGINT) 
# от Docker при выполнении docker compose down.

exec /usr/local/bin/supercronic "$CRON_FILE"
